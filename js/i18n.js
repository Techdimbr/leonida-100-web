window.I18n = (function () {
  const STORAGE_KEY = 'leonida_lang';

  function detectLang() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && window.LEONIDA_I18N[saved]) return saved;
    const nav = (navigator.language || 'en-US').toLowerCase();
    return nav.startsWith('pt') ? 'pt-BR' : 'en-US';
  }

  let current = detectLang();

  function t(key) {
    return (window.LEONIDA_I18N[current] && window.LEONIDA_I18N[current][key]) || key;
  }

  function applyDOM() {
    document.documentElement.lang = current;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', t(key));
    });
    document.querySelectorAll('.lang-btn').forEach((btn) => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === current);
    });
    // Reorder checkout buttons subtly so local currency store stands out first
    const ptStores = document.querySelectorAll('[data-store-region="br"]');
    const globalStores = document.querySelectorAll('[data-store-region="global"]');
    if (ptStores.length && globalStores.length) {
      ptStores.forEach((el) => {
        el.classList.toggle('btn-primary', current === 'pt-BR' && el.id === 'btn-kirvano');
        el.classList.toggle('btn-secondary', !(current === 'pt-BR' && el.id === 'btn-kirvano'));
      });
      globalStores.forEach((el) => {
        el.classList.toggle('btn-primary', current === 'en-US' && el.id === 'btn-payhip');
        el.classList.toggle('btn-secondary', !(current === 'en-US' && el.id === 'btn-payhip'));
      });
    }
  }

  function setLang(lang) {
    if (!window.LEONIDA_I18N[lang]) return;
    current = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    applyDOM();
    window.dispatchEvent(new CustomEvent('leonida:langchange', { detail: { lang } }));
  }

  function init() {
    document.querySelectorAll('.lang-btn').forEach((btn) => {
      btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang')));
    });
    // Wire configured checkout links
    const cfg = window.LEONIDA_CONFIG.checkoutLinks;
    Object.keys(cfg).forEach((k) => {
      const el = document.getElementById('btn-' + k);
      if (el) el.setAttribute('href', cfg[k]);
    });
    applyDOM();
  }

  return {
    get lang() { return current; },
    t,
    setLang,
    applyDOM,
    init
  };
})();
